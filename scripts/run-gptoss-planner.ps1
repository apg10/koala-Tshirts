param(
  [string]$Model = "gptoss20-reviewer",
  [string]$RepoRoot = "C:\Users\adria\Programacion\Programacion\koala-tshirts"
)

$ErrorActionPreference = "Stop"

if (-not (Get-Command ollama -ErrorAction SilentlyContinue)) {
  throw "ollama was not found in PATH."
}

$repo = (Resolve-Path -LiteralPath $RepoRoot).Path
$reportPath = Join-Path $repo "08-PLANNER-REPORT.md"

function Read-RepoFile {
  param([string]$RelativePath)

  $path = Join-Path $repo $RelativePath
  if (-not (Test-Path -LiteralPath $path)) {
    return "## FILE MISSING: $RelativePath`n"
  }

  $content = Get-Content -LiteralPath $path -Raw
  return @"
## FILE: $RelativePath

$content

"@
}

Push-Location $repo
try {
  $gitStatus = git status --short
  $gitLog = git log --oneline -20
}
finally {
  Pop-Location
}

$context = @(
  (Read-RepoFile "06-PLANNER-PROTOCOL.md"),
  (Read-RepoFile "07-PLANNER-CONTEXT.md"),
  (Read-RepoFile "00-PLAN.md"),
  (Read-RepoFile "02-LOG.md"),
  (Read-RepoFile "05-WORKER-RESULT.md"),
  (Read-RepoFile "09-LOCAL-MODEL-TASK-QUEUE.md")
) -join "`n"

$prompt = @"
You are Offline Planner for the Koala ecommerce repository.

You are not a developer. Do not produce code patches. Do not suggest direct file edits except future handoff candidates.

Use the repository context below to produce a concise Markdown report.

The report must include:
1. Current implementation phase.
2. Recent completed work.
3. Validation status.
4. Git/worktree concerns.
5. Roadmap drift or inconsistencies.
6. Current risks.
7. The next 3 local-worker micro-task candidates.
8. Tasks that require Cloud Control before delegation.
9. One recommended next handoff candidate.

Important:
- Do not claim tasks are complete without validation evidence.
- If roadmap and log disagree, call it drift.
- Checkout, Stripe, payment, order lifecycle, and auth security design require Cloud Control first.
- Keep the report concise and factual.
- Output only Markdown for 08-PLANNER-REPORT.md.

## GIT STATUS --SHORT

$($gitStatus -join "`n")

## GIT LOG --ONELINE -20

$($gitLog -join "`n")

## REPOSITORY CONTEXT

$context
"@

$promptPath = Join-Path $env:TEMP "koala-gptoss-planner-prompt.md"
$prompt | Set-Content -LiteralPath $promptPath -Encoding UTF8

$report = Get-Content -LiteralPath $promptPath -Raw | ollama run $Model

if (-not $report -or -not ($report -join "").Trim()) {
  throw "Planner model returned an empty report."
}

$header = @"
# Offline Planner Report

Generated by: `$Model`
Generated at: $(Get-Date -Format "yyyy-MM-dd HH:mm:ss zzz")

"@

($header + ($report -join "`n")) | Set-Content -LiteralPath $reportPath -Encoding UTF8

Write-Host "Planner report written to $reportPath"
